    /**
     * 특정 날짜에 맞춘 고유한 1000개의 현실적인 현대인 일기를 절차적으로 생성합니다.
     */
    fun generate1000Diaries(dateString: String): List<StarDiary> {
        val seed = dateString.hashCode().toLong()
        val random = Random(seed)

        val list = ArrayList<StarDiary>(1000)

        for (i in 1..1000) {
            val origin = origins[random.nextInt(origins.size)]
            val sentence = modernDiarySentences[random.nextInt(modernDiarySentences.size)]
            val prefix = prefixes[random.nextInt(prefixes.size)]
            val suffix = suffixes[random.nextInt(suffixes.size)]

            // 자연스러운 문장 조합
            val fullContent = if (prefix.isNotBlank() && !sentence.startsWith(prefix.trim())) {
                "$prefix$sentence$suffix"
            } else {
                "$sentence$suffix"
            }

            list.add(
                StarDiary(
                    id = "diary-$dateString-$i",
                    content = fullContent.trim(),
                    universeOrigin = origin,
                    date = dateString,
                    timestamp = seed + i
                )
            )
        }

        return list
    }
